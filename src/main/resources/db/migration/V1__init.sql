-- Paiements Mobile Money. Montants en XOF (pas de centimes) : BIGINT.
CREATE TABLE payments (
    id                 UUID         PRIMARY KEY,
    amount             BIGINT       NOT NULL CHECK (amount > 0),
    currency           VARCHAR(3)   NOT NULL,
    provider           VARCHAR(16)  NOT NULL,
    payer_phone        VARCHAR(20)  NOT NULL,
    merchant_reference VARCHAR(64)  NOT NULL,
    provider_reference VARCHAR(64)  UNIQUE,
    status             VARCHAR(16)  NOT NULL,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    version            BIGINT       NOT NULL
);

-- Une clé d'idempotence = un seul paiement, garanti par la clé primaire.
CREATE TABLE idempotency_records (
    idempotency_key VARCHAR(100) PRIMARY KEY,
    request_hash    VARCHAR(64)  NOT NULL,
    payment_id      UUID         NOT NULL REFERENCES payments (id),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Journal d'audit en ajout seul.
CREATE TABLE audit_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    action      VARCHAR(64)  NOT NULL,
    payment_id  UUID,
    details     VARCHAR(500)
);

CREATE INDEX idx_audit_events_payment ON audit_events (payment_id);
